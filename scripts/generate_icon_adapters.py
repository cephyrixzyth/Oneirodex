"""Generate framework adapters from the neutral shared SVG icon manifest."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = ROOT / 'frontend' / 'shared' / 'icons' / 'manifest.json'
REACT_OUTPUT = ROOT / 'frontend' / 'shared' / 'src' / 'generatedIconPaths.tsx'
SVG_TAGS = {'circle', 'ellipse', 'line', 'path', 'polygon', 'polyline', 'rect'}
SVG_ATTRIBUTES = {
    'cx', 'cy', 'd', 'fill', 'height', 'points', 'r', 'rx', 'ry', 'stroke',
    'stroke-linecap', 'stroke-linejoin', 'stroke-width', 'width', 'x', 'x1',
    'x2', 'y', 'y1', 'y2',
}
SAFE_VALUE = re.compile(r'^[\w\s.,#%+\-/]*$')


def validate_manifest(manifest: dict[str, Any]) -> dict[str, Any]:
    if manifest.get('schema_version') != 1:
        raise ValueError('unsupported icon manifest schema_version')
    if not isinstance(manifest.get('view_box'), str) or not SAFE_VALUE.fullmatch(manifest['view_box']):
        raise ValueError('view_box must be a plain SVG viewBox value')
    icons = manifest.get('icons')
    if not isinstance(icons, dict) or not icons:
        raise ValueError('icons must be a non-empty object')
    canonical = set(icons)
    aliases: set[str] = set()
    for key, icon in icons.items():
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', key):
            raise ValueError(f'invalid semantic key: {key!r}')
        if not isinstance(icon.get('category'), str) or not icon['category']:
            raise ValueError(f'{key}: category is required')
        if not isinstance(icon.get('accessible_use'), str) or not icon['accessible_use']:
            raise ValueError(f'{key}: accessible_use is required')
        aliases_for_icon = icon.get('aliases', [])
        if not isinstance(aliases_for_icon, list):
            raise ValueError(f'{key}: aliases must be a list')
        for alias in aliases_for_icon:
            if not isinstance(alias, str) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', alias):
                raise ValueError(f'{key}: invalid alias {alias!r}')
            if alias in canonical or alias in aliases:
                raise ValueError(f'duplicate alias/canonical key: {alias}')
            aliases.add(alias)
        theme = icon.get('theme', {})
        if theme.get('mode') not in {'inherit', 'override'}:
            raise ValueError(f'{key}: theme mode must be inherit or override')
        if theme['mode'] == 'override' and not isinstance(theme.get('variants'), dict):
            raise ValueError(f'{key}: override needs a variants object')
        shapes = icon.get('shapes')
        if not isinstance(shapes, list) or not shapes:
            raise ValueError(f'{key}: shapes must be a non-empty list')
        for shape in shapes:
            if shape.get('tag') not in SVG_TAGS:
                raise ValueError(f"{key}: unsupported SVG tag {shape.get('tag')!r}")
            attributes = shape.get('attributes')
            if not isinstance(attributes, dict) or not attributes:
                raise ValueError(f'{key}: shape attributes are required')
            for attr, value in attributes.items():
                if attr not in SVG_ATTRIBUTES:
                    raise ValueError(f'{key}: unsupported SVG attribute {attr!r}')
                if not isinstance(value, str) or not SAFE_VALUE.fullmatch(value):
                    raise ValueError(f'{key}: unsafe SVG attribute value for {attr!r}')
    for key, icon in icons.items():
        variants = icon.get('theme', {}).get('variants', {})
        if any(ref not in canonical for ref in variants.values()):
            raise ValueError(f'{key}: theme variant references an unknown key')
    return manifest


def load_manifest() -> dict[str, Any]:
    return validate_manifest(json.loads(MANIFEST_PATH.read_text(encoding='utf-8')))


def to_react_attribute(name: str) -> str:
    return {
        'stroke-linecap': 'strokeLinecap',
        'stroke-linejoin': 'strokeLinejoin',
        'stroke-width': 'strokeWidth',
    }.get(name, name)


def generate_react(manifest: dict[str, Any]) -> str:
    lines = [
        '// Generated by scripts/generate_icon_adapters.py; edit frontend/shared/icons/manifest.json.',
        "import type { ReactNode } from 'react'",
        '',
        'export const sharedIconPaths: Record<string, ReactNode> = {',
    ]
    for key, icon in manifest['icons'].items():
        for name in [key, *icon.get('aliases', [])]:
            member = name if re.fullmatch(r'[A-Za-z_$][\w$]*', name) else f"'{name}'"
            lines.append(f"  {member}: (")
            lines.append('    <>')
            for shape in icon['shapes']:
                attrs = ' '.join(
                    f'{to_react_attribute(attr)}="{value}"'
                    for attr, value in shape['attributes'].items()
                )
                if len(shape['tag']) + len(attrs) < 78:
                    lines.append(f"      <{shape['tag']} {attrs} />")
                else:
                    lines.append(f"      <{shape['tag']}")
                    for attr, value in shape['attributes'].items():
                        lines.append(f"        {to_react_attribute(attr)}=\"{value}\"")
                    lines.append('      />')
            lines.extend(['    </>', '  ),'])
    lines.extend(['}', '', 'export const sharedIconAliases: Record<string, string> = {'])
    for key, icon in manifest['icons'].items():
        for alias in icon.get('aliases', []):
            lines.append(f"  '{alias}': '{key}',")
    lines.extend(['}', ''])
    return '\n'.join(lines)


def outputs() -> dict[Path, str]:
    manifest = load_manifest()
    return {REACT_OUTPUT: generate_react(manifest)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated adapters are stale')
    args = parser.parse_args()
    try:
        generated = outputs()
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f'icon manifest error: {exc}', file=sys.stderr)
        return 1
    stale = []
    for path, content in generated.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    if stale:
        print('stale icon adapters: ' + ', '.join(stale), file=sys.stderr)
        return 1
    print('icon adapters are current' if args.check else 'generated icon adapters')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
